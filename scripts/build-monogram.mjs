// Generates src/lib/monogram-data.js: the joined "J" + "F" monogram as SVG outlines
// (Great Vibes, OFL - the same script as the names), so the seal/loader never depend on web-font loading.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const root = new URL('..', import.meta.url);
const font = opentype.parse(readFileSync(fileURLToPath(new URL('scripts/fonts/GreatVibes-Regular.ttf', root))).buffer);

const SIZE = 100;
const OVERLAP = 0.14; // how far B tucks into S, in em: strokes touch, both letters stay clear
const [first, second] = ['J', 'F'];

const g1 = font.charToGlyph(first);
const g2 = font.charToGlyph(second);
const x2 = (g1.advanceWidth / font.unitsPerEm - OVERLAP) * SIZE;
const p1 = g1.getPath(0, SIZE, SIZE);
const p2 = g2.getPath(x2, SIZE, SIZE);

const b1 = p1.getBoundingBox();
const b2 = p2.getBoundingBox();
const pad = 2;
const minX = Math.min(b1.x1, b2.x1) - pad;
const minY = Math.min(b1.y1, b2.y1) - pad;
const w = Math.max(b1.x2, b2.x2) - minX + pad;
const h = Math.max(b1.y2, b2.y2) - minY + pad;

const shift = (path) => {
  for (const c of path.commands) {
    for (const k of ['x', 'y', 'x1', 'y1', 'x2', 'y2']) {
      // round here: opentype's own rounding turns tiny leftovers such as 1.4e-14 into "NaN"
      if (c[k] !== undefined) c[k] = Math.round((c[k] - (k.startsWith('x') ? minX : minY)) * 100) / 100;
    }
  }
  return path.toPathData(2);
};

// Outline length (all sub-paths), used for the stroke-draw animation.
const length = (path) => {
  let len = 0;
  let x = 0, y = 0, sx = 0, sy = 0;
  const seg = (fn) => {
    let px = x, py = y;
    for (let i = 1; i <= 24; i++) {
      const [nx, ny] = fn(i / 24);
      len += Math.hypot(nx - px, ny - py);
      px = nx; py = ny;
    }
  };
  for (const c of path.commands) {
    if (c.type === 'M') { x = sx = c.x; y = sy = c.y; continue; }
    if (c.type === 'L') { len += Math.hypot(c.x - x, c.y - y); }
    else if (c.type === 'Q') {
      seg((t) => [(1 - t) ** 2 * x + 2 * (1 - t) * t * c.x1 + t * t * c.x, (1 - t) ** 2 * y + 2 * (1 - t) * t * c.y1 + t * t * c.y]);
    } else if (c.type === 'C') {
      seg((t) => [
        (1 - t) ** 3 * x + 3 * (1 - t) ** 2 * t * c.x1 + 3 * (1 - t) * t * t * c.x2 + t ** 3 * c.x,
        (1 - t) ** 3 * y + 3 * (1 - t) ** 2 * t * c.y1 + 3 * (1 - t) * t * t * c.y2 + t ** 3 * c.y,
      ]);
    } else if (c.type === 'Z') { len += Math.hypot(sx - x, sy - y); x = sx; y = sy; continue; }
    x = c.x; y = c.y;
  }
  return Math.ceil(len);
};

const d1 = shift(p1);
const d2 = shift(p2);
const out = `// Generated by scripts/build-monogram.mjs - do not edit by hand.
export const MONOGRAM = {
  viewBox: '0 0 ${w.toFixed(2)} ${h.toFixed(2)}',
  width: ${w.toFixed(2)},
  height: ${h.toFixed(2)},
  first: '${d1}',
  firstLength: ${length(p1)},
  second: '${d2}',
  secondLength: ${length(p2)},
};
`;
writeFileSync(fileURLToPath(new URL('src/lib/monogram-data.js', root)), out);

// Favicon: gold monogram on a rose-gold wax disc.
const fs = 72 / w;
const favicon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">
<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#C9A55E"/><stop offset=".45" stop-color="#F6E6B4"/><stop offset="1" stop-color="#A8843F"/></linearGradient>
<radialGradient id="w" cx=".38" cy=".32" r=".8"><stop offset="0" stop-color="#E9C1B6"/><stop offset=".55" stop-color="#B07468"/><stop offset="1" stop-color="#6C3D37"/></radialGradient></defs>
<circle cx="50" cy="50" r="48" fill="url(#w)"/>
<g transform="translate(${(50 - (w * fs) / 2).toFixed(2)} ${(50 - (h * fs) / 2).toFixed(2)}) scale(${fs.toFixed(4)})" fill="url(#g)"><path d="${d1}"/><path d="${d2}"/></g>
</svg>
`;
writeFileSync(fileURLToPath(new URL('public/favicon.svg', root)), favicon);
